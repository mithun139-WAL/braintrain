"""
Hallucination Validator.

Validates generated interview questions and responses to prevent hallucinations:
- Checks against verified candidate profile
- Validates entity references
- Ensures grounding in retrieved knowledge
"""
from typing import Dict, Any, List, Optional
import logging

from app.ai.intelligence.rules.hallucination_rules import HallucinationRuleEngine
from app.ai.intelligence.rules.rule_engine import RuleSeverity

logger = logging.getLogger(__name__)


class HallucinationValidator:
    """
    Validates generated content to prevent hallucinations.
    
    Uses the HallucinationRuleEngine to check generated questions
    and responses before they're presented to candidates.
    """
    
    def __init__(self):
        self.rule_engine = HallucinationRuleEngine()
        self._validation_count = 0
        self._blocked_count = 0
    
    def validate_question(
        self,
        generated_question: str,
        verified_profile: Dict[str, Any],
        conversation_history: List[Dict[str, Any]],
        retrieved_context: Optional[List[Dict[str, Any]]] = None
    ) -> tuple[bool, str, Dict[str, Any]]:
        """
        Validate a generated question for hallucinations.
        
        Args:
            generated_question: The question generated by LLM
            verified_profile: Verified candidate profile data
            conversation_history: Previous conversation turns
            retrieved_context: Retrieved knowledge chunks (if any)
            
        Returns:
            (is_valid, reason, details)
            - is_valid: True if question passes validation
            - reason: Explanation of validation result
            - details: Additional validation details
        """
        self._validation_count += 1
        
        # Build context for rule engine
        context = {
            "generated_question": generated_question,
            "verified_profile": verified_profile,
            "conversation_history": conversation_history,
            "retrieved_context": retrieved_context or []
        }
        
        # Evaluate all hallucination rules
        violations = self.rule_engine.evaluate_all(context)
        
        # Check for blocker violations
        blockers = self.rule_engine.get_blocker_violations(violations)
        
        if blockers:
            self._blocked_count += 1
            reasons = [v.reason for v in blockers]
            
            logger.warning(
                f"Question blocked due to hallucination risk: {'; '.join(reasons)}",
                extra={
                    "question": generated_question[:100],
                    "blocker_count": len(blockers)
                }
            )
            
            return False, f"Hallucination detected: {'; '.join(reasons)}", {
                "violations": [v.reason for v in blockers],
                "blocked_rules": [v.rule.id for v in blockers]
            }
        
        # Check for warnings
        warnings = [v for v in violations if v.violated and v.rule.severity == RuleSeverity.WARNING]
        
        if warnings:
            warning_reasons = [v.reason for v in warnings]
            logger.info(
                f"Question validated with warnings: {'; '.join(warning_reasons)}",
                extra={"question": generated_question[:100]}
            )
            
            return True, f"Valid with warnings: {'; '.join(warning_reasons)}", {
                "warnings": warning_reasons,
                "warning_rules": [v.rule.id for v in warnings]
            }
        
        logger.debug(
            f"Question validated successfully",
            extra={"question": generated_question[:100]}
        )
        
        return True, "Valid question", {}
    
    def validate_followup(
        self,
        generated_followup: str,
        candidate_last_response: str,
        verified_profile: Dict[str, Any],
        conversation_history: List[Dict[str, Any]]
    ) -> tuple[bool, str, Dict[str, Any]]:
        """
        Validate a generated follow-up question.
        
        Args:
            generated_followup: The follow-up question generated by LLM
            candidate_last_response: Candidate's most recent response
            verified_profile: Verified candidate profile data
            conversation_history: Previous conversation turns
            
        Returns:
            (is_valid, reason, details)
        """
        self._validation_count += 1
        
        # Build context for rule engine
        context = {
            "generated_question": generated_followup,
            "generated_followup": generated_followup,
            "candidate_last_response": candidate_last_response,
            "verified_profile": verified_profile,
            "conversation_history": conversation_history
        }
        
        # Evaluate hallucination rules
        violations = self.rule_engine.evaluate_all(context)
        
        # Check for blockers
        blockers = self.rule_engine.get_blocker_violations(violations)
        
        if blockers:
            self._blocked_count += 1
            reasons = [v.reason for v in blockers]
            
            logger.warning(
                f"Follow-up blocked due to hallucination risk: {'; '.join(reasons)}",
                extra={"followup": generated_followup[:100]}
            )
            
            return False, f"Hallucination detected: {'; '.join(reasons)}", {
                "violations": [v.reason for v in blockers],
                "blocked_rules": [v.rule.id for v in blockers]
            }
        
        return True, "Valid follow-up", {}
    
