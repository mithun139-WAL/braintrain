    def suggest_correction(
        self,
        invalid_question: str,
        verification_failure: Dict[str, Any]
    ) -> str:
        """
        Suggest a corrected version of an invalid question.
        
        Args:
            invalid_question: The question that failed validation
            verification_failure: Details of why validation failed
            
        Returns:
            Suggested correction or guidance
        """
        blocked_rules = verification_failure.get("blocked_rules", [])
        
        if "no_unverified_assumption" in blocked_rules:
            return "Rephrase without assuming unverified candidate experience. Ask open-ended questions to gather information first."
        
        if "no_invented_projects" in blocked_rules:
            return "Remove specific project references. Ask candidate to describe their experience first."
        
        if "no_assumed_tech_stack" in blocked_rules:
            return "Remove assumed technology references. Ask candidate what technologies they used."
        
        return "Rephrase question to avoid unverified assumptions about candidate background."
    
    def get_metrics(self) -> Dict[str, Any]:
        """Get validation metrics."""
        validation_rate = (
            (self._validation_count - self._blocked_count) / self._validation_count 
            if self._validation_count > 0 else 1.0
        )
        
        return {
            "validation_count": self._validation_count,
            "blocked_count": self._blocked_count,
            "validation_rate": validation_rate,
            "block_rate": 1.0 - validation_rate
        }
    
    def reset_metrics(self) -> None:
        """Reset validation metrics."""
        self._validation_count = 0
        self._blocked_count = 0
